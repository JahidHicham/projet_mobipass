CREATE TABLE PAYS (
  CodePays CHAR(2) NOT NULL,
  NomPays VARCHAR(50) NOT NULL,
  TauxTVA DECIMAL(4,3) NOT NULL,
  PRIMARY KEY (CodePays)
);

CREATE TABLE ZONE_GEO (
  CodeZG VARCHAR(10) NOT NULL,
  NomZG VARCHAR(100) NOT NULL,
  NiveauZG VARCHAR(20) NOT NULL,
  CodePays CHAR(2) NOT NULL,
  CodeZG_Sup VARCHAR(10),
  PRIMARY KEY (CodeZG),
  FOREIGN KEY (CodePays) REFERENCES PAYS (CodePays),
  FOREIGN KEY (CodeZG_Sup) REFERENCES ZONE_GEO (CodeZG)
);

CREATE TABLE DOMAINE (
  CodeDO VARCHAR(7) NOT NULL,
  NomDO VARCHAR(100) NOT NULL,
  CodeDO_Sup VARCHAR(7),
  PRIMARY KEY (CodeDO),
  FOREIGN KEY (CodeDO_Sup) REFERENCES DOMAINE (CodeDO)
);

CREATE TABLE CATEGORIE_JURIDIQUE (
  CodeCJ VARCHAR(4) NOT NULL,
  LibelleCJ VARCHAR(150) NOT NULL,
  NiveauCJ INT NOT NULL,
  CodeCJ_Sup VARCHAR(4),
  PRIMARY KEY (CodeCJ),
  FOREIGN KEY (CodeCJ_Sup) REFERENCES CATEGORIE_JURIDIQUE (CodeCJ)
);

CREATE TABLE SOCIETE (
  CodeSOC VARCHAR(14) NOT NULL,
  NomSOC VARCHAR(100) NOT NULL,
  TypeSOC VARCHAR(30),
  CodeDO VARCHAR(7) NOT NULL,
  CodeCJ VARCHAR(4),
  CodeZG VARCHAR(10) NOT NULL,
  PRIMARY KEY (CodeSOC),
  FOREIGN KEY (CodeDO) REFERENCES DOMAINE (CodeDO),
  FOREIGN KEY (CodeCJ) REFERENCES CATEGORIE_JURIDIQUE (CodeCJ),
  FOREIGN KEY (CodeZG) REFERENCES ZONE_GEO (CodeZG)
);

CREATE TABLE SERVICE (
  CodeSE INT NOT NULL,
  NomSE VARCHAR(50) NOT NULL,
  CodeSOC VARCHAR(14) NOT NULL,
  PRIMARY KEY (CodeSE),
  FOREIGN KEY (CodeSOC) REFERENCES SOCIETE (CodeSOC)
);

CREATE TABLE CATEGORIE (
  CodeCAT CHAR(5) NOT NULL,
  NomCAT VARCHAR(100) NOT NULL,
  SuperCAT VARCHAR(100) NOT NULL,
  PRIMARY KEY (CodeCAT)
);

CREATE TABLE EMPLOYE (
  CodeE INT NOT NULL,
  NomE VARCHAR(50) NOT NULL,
  PrenomE VARCHAR(50) NOT NULL,
  MatriculeSAL VARCHAR(20),
  SIRET VARCHAR(14),
  DateNaissE DATE,
  DateEntreeE DATE,
  CPResidenceE VARCHAR(10),
  CodeCAT CHAR(5) NOT NULL,
  CodeSE INT NOT NULL,
  PRIMARY KEY (CodeE),
  FOREIGN KEY (CodeCAT) REFERENCES CATEGORIE (CodeCAT),
  FOREIGN KEY (CodeSE) REFERENCES SERVICE (CodeSE)
);

CREATE TABLE GRAND_DOMAINE (
  CodeGD CHAR(1) NOT NULL,
  LibelleGD VARCHAR(100) NOT NULL,
  PRIMARY KEY (CodeGD)
);

CREATE TABLE DOMAINE_PRO (
  CodeDP CHAR(3) NOT NULL,
  LibelleDP VARCHAR(150) NOT NULL,
  CodeGD CHAR(1) NOT NULL,
  PRIMARY KEY (CodeDP),
  FOREIGN KEY (CodeGD) REFERENCES GRAND_DOMAINE (CodeGD)
);

CREATE TABLE FICHE_METIER (
  CodeROME CHAR(5) NOT NULL,
  LibelleMetier VARCHAR(150) NOT NULL,
  CodeDP CHAR(3) NOT NULL,
  PRIMARY KEY (CodeROME),
  FOREIGN KEY (CodeDP) REFERENCES DOMAINE_PRO (CodeDP)
);

CREATE TABLE APPELLATION (
  CodeAPP VARCHAR(6) NOT NULL,
  LibelleAPP VARCHAR(200) NOT NULL,
  CodeROME CHAR(5) NOT NULL,
  PRIMARY KEY (CodeAPP),
  FOREIGN KEY (CodeROME) REFERENCES FICHE_METIER (CodeROME)
);

CREATE TABLE EXERCER (
  CodeE INT NOT NULL,
  DateDebutMetier DATE NOT NULL,
  CodeAPP VARCHAR(6) NOT NULL,
  DateFinMetier DATE,
  TypeContrat VARCHAR(20) NOT NULL,
  PRIMARY KEY (CodeE, DateDebutMetier),
  FOREIGN KEY (CodeE) REFERENCES EMPLOYE (CodeE),
  FOREIGN KEY (CodeAPP) REFERENCES APPELLATION (CodeAPP)
);

CREATE TABLE FABRICANT (
  CodeFAB VARCHAR(10) NOT NULL,
  NomFAB VARCHAR(50) NOT NULL,
  PaysFAB VARCHAR(50),
  PRIMARY KEY (CodeFAB)
);

CREATE TABLE GENERATION (
  CodeGEN VARCHAR(10) NOT NULL,
  NomGEN VARCHAR(50) NOT NULL,
  DateSortieGEN DATE NOT NULL,
  DateArretGEN DATE,
  CodeFAB VARCHAR(10) NOT NULL,
  PRIMARY KEY (CodeGEN),
  FOREIGN KEY (CodeFAB) REFERENCES FABRICANT (CodeFAB)
);

CREATE TABLE GAMME (
  CodeG CHAR(5) NOT NULL,
  NomG VARCHAR(50) NOT NULL,
  SecteurG VARCHAR(50) NOT NULL,
  PRIMARY KEY (CodeG)
);

CREATE TABLE PRODUIT (
  CodeP INT NOT NULL,
  NomP VARCHAR(50) NOT NULL,
  MarqueP VARCHAR(50),
  DescriptifP VARCHAR(500),
  PoidsKg DECIMAL(6,2),
  AutonomieKm INT,
  CodeG CHAR(5) NOT NULL,
  CodeGEN VARCHAR(10) NOT NULL,
  PRIMARY KEY (CodeP),
  FOREIGN KEY (CodeG) REFERENCES GAMME (CodeG),
  FOREIGN KEY (CodeGEN) REFERENCES GENERATION (CodeGEN)
);

CREATE TABLE TARIF (
  CodeP INT NOT NULL,
  CodePays CHAR(2) NOT NULL,
  DateDebutTarif DATE NOT NULL,
  DateFinTarif DATE,
  Prix_loc_jour DECIMAL(10,2),
  Prix_vente DECIMAL(10,2) NOT NULL,
  ModePrix VARCHAR(3) NOT NULL,
  PRIMARY KEY (CodeP, CodePays, DateDebutTarif),
  FOREIGN KEY (CodeP) REFERENCES PRODUIT (CodeP),
  FOREIGN KEY (CodePays) REFERENCES PAYS (CodePays)
);

CREATE TABLE AGENCE (
  CodeAG VARCHAR(10) NOT NULL,
  NomAG VARCHAR(50) NOT NULL,
  VilleAG VARCHAR(50) NOT NULL,
  CodePays CHAR(2) NOT NULL,
  PRIMARY KEY (CodeAG),
  FOREIGN KEY (CodePays) REFERENCES PAYS (CodePays)
);

CREATE TABLE EXEMPLAIRE (
  CodeEX INT NOT NULL,
  NumSerieEX VARCHAR(30) NOT NULL,
  DateMiseServiceEX DATE NOT NULL,
  DateReformeEX DATE,
  CodeP INT NOT NULL,
  CodeAG VARCHAR(10) NOT NULL,
  PRIMARY KEY (CodeEX),
  FOREIGN KEY (CodeP) REFERENCES PRODUIT (CodeP),
  FOREIGN KEY (CodeAG) REFERENCES AGENCE (CodeAG)
);

CREATE TABLE REDUCTION (
  CodeG CHAR(5) NOT NULL,
  CodeCAT CHAR(5) NOT NULL,
  Annee INT NOT NULL,
  PctReduc_Loc DECIMAL(4,3) NOT NULL,
  PctReduc_Achat DECIMAL(4,3) NOT NULL,
  PRIMARY KEY (CodeG, CodeCAT, Annee),
  FOREIGN KEY (CodeG) REFERENCES GAMME (CodeG),
  FOREIGN KEY (CodeCAT) REFERENCES CATEGORIE (CodeCAT)
);

CREATE TABLE ACHAT (
  CodeP INT NOT NULL,
  CodeE INT NOT NULL,
  DateA DATE NOT NULL,
  Qte INT NOT NULL,
  PRIMARY KEY (CodeP, CodeE, DateA),
  FOREIGN KEY (CodeP) REFERENCES PRODUIT (CodeP),
  FOREIGN KEY (CodeE) REFERENCES EMPLOYE (CodeE)
);

CREATE TABLE RESERVER (
  CodeP INT NOT NULL,
  CodeE INT NOT NULL,
  DateLPrev DATE NOT NULL,
  Nb_Ex_Prev INT NOT NULL,
  DateResa DATE NOT NULL,
  Duree_Prev INT NOT NULL,
  PRIMARY KEY (CodeP, CodeE, DateLPrev),
  FOREIGN KEY (CodeP) REFERENCES PRODUIT (CodeP),
  FOREIGN KEY (CodeE) REFERENCES EMPLOYE (CodeE)
);

CREATE TABLE LOUER (
  CodeEX INT NOT NULL,
  CodeE INT NOT NULL,
  DateL DATE NOT NULL,
  Duree_Loc INT NOT NULL,
  PRIMARY KEY (CodeEX, CodeE, DateL),
  FOREIGN KEY (CodeEX) REFERENCES EXEMPLAIRE (CodeEX),
  FOREIGN KEY (CodeE) REFERENCES EMPLOYE (CodeE)
);
